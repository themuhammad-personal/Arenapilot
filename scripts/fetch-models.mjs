#!/usr/bin/env node
// Regenerate `models.json` — the model list the app serves to the site's picker.
//
// Why this exists
// ---------------
// The picker is only as good as the list behind it, and the list changes weekly.
// Fetched once inside a WebView it is gone as soon as the page caches anything;
// fetched from OkHttp it is refused (the endpoint is behind the site's own
// challenge). So the app keeps a cached copy, serves it when the live request
// fails, and this script keeps that copy honest by rebuilding it from the same
// public catalog the site itself loads:
//
//     GET https://arena.ai/nextjs-api/model-catalog
//     [ { "arena": "text", "models": [ { id, publicName, displayName,
//                                        organization, capabilities, … } ] }, … ]
//
// The legacy `/api/model-catalog` prefix answers 403 "Route not allowed", and
// `/nextjs-api/stream/...` is the chat path — neither is a model list. Verified
// against the site's own network traffic (see docs/).
//
// What is kept, and why it is small
// ---------------------------------
// Only what a picker needs: the id it sends back, the name a person reads, and the
// provider as a secondary label. Dropping capabilities/ranks/providers takes the
// file from ~157 KB to a few KB — small enough to travel in one bridge reply and
// to live in the APK, which is what makes the picker work on the first launch
// with no network at all.
//
// Usage
//   node scripts/fetch-models.mjs            # write models.json
//   node scripts/fetch-models.mjs --check    # exit 1 when the file is stale
//   node scripts/fetch-models.mjs --input snapshot.json   # offline: use a saved catalog
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const CATALOG_URL = 'https://arena.ai/nextjs-api/model-catalog';
export const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'models.json');
/** Direct Chat is the text arena; image/video arenas are separate products. */
export const ARENAS = ['text', 'code'];

/**
 * Trim one catalog entry to { id, name, provider }.
 *
 * `publicName` is what the site's picker shows and what chat requests carry;
 * `displayName` is the same string today but is the nicer label when the site sets
 * one, so it wins when it differs. An entry without an id or a public name cannot
 * be picked at all and is dropped rather than served as a dead row.
 */
export function trimModel(model) {
  if (!model || typeof model !== 'object') return null;
  const id = String(model.id || '').trim();
  const publicName = String(model.publicName || model.name || '').trim();
  if (!id || !publicName) return null;
  const display = String(model.displayName || '').trim();
  const name = display && display !== publicName ? display : publicName;
  const provider = String(model.organization || '').trim();
  return { id, name: name || publicName, provider };
}

/**
 * The catalog is a list of `{ arena, models }` categories; some deployments return
 * a single object or a flat array. All three shapes are accepted, because this
 * script must not be the reason a build fails on a Tuesday.
 */
export function collect(catalog, arenas = ARENAS) {
  const categories = Array.isArray(catalog) ? catalog : catalog && Array.isArray(catalog.categories) ? catalog.categories : [];
  const out = new Map();
  const selected = new Set(arenas);
  for (const category of categories) {
    const arena = String(category && category.arena ? category.arena : '');
    // An unlabelled category carries every model; a labelled one is filtered.
    if (arena && !selected.has(arena)) continue;
    for (const raw of category.models || []) {
      const m = trimModel(raw);
      if (!m) continue;
      // One model can sit in several arenas: keep the first (richest is identical).
      if (!out.has(m.id)) out.set(m.id, m);
    }
  }
  return [...out.values()].sort((a, b) => (a.provider || '').localeCompare(b.provider || '') || a.name.localeCompare(b.name));
}

/** The file as it is written: stable ordering, so a rebuild only changes real edits. */
export function document(models, { updated = new Date().toISOString().slice(0, 10) } = {}) {
  return {
    version: 1,
    updated,
    source: CATALOG_URL,
    arenas: ARENAS,
    note:
      'The model list this app serves to arena.ai\'s picker. Regenerated by scripts/fetch-models.mjs from the site\'s own public catalog, ' +
      'trimmed to what a picker needs. Shipped inside the APK (first launch works offline) and published as the "models" release asset. ' +
      'The app prefers a live response from the site and falls back to this file.',
    models,
  };
}

async function main() {
  const argv = process.argv.slice(2);
  const check = argv.includes('--check');
  const inputAt = argv.indexOf('--input');
  let catalog;
  if (inputAt >= 0) {
    catalog = JSON.parse(fs.readFileSync(argv[inputAt + 1], 'utf8'));
  } else {
    const res = await fetch(CATALOG_URL, {
      headers: {
        // The endpoint is public JSON; a browser UA keeps it from being treated
        // as a bot (the same reason the app's own fetch sets one).
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36',
        Accept: 'application/json',
      },
    });
    if (!res.ok) {
      console.error(`catalog fetch failed: HTTP ${res.status} ${CATALOG_URL}`);
      process.exit(1);
    }
    catalog = await res.json();
  }

  const models = collect(catalog);
  if (models.length === 0) {
    console.error('the catalog produced no usable models — refusing to write an empty list');
    process.exit(1);
  }

  const previous = fs.existsSync(OUT) ? JSON.parse(fs.readFileSync(OUT, 'utf8')) : null;
  const next = document(models, { updated: previous?.updated });
  const text = JSON.stringify(next, null, 2) + '\n';

  if (check) {
    const before = previous ? JSON.stringify(previous.models) : '';
    if (before !== JSON.stringify(next.models)) {
      console.error(`models.json is stale: ${previous ? previous.models.length : 0} models on disk, ${models.length} live`);
      process.exit(1);
    }
    console.log(`models.json is current (${models.length} models)`);
    return;
  }

  // Keep the previous `updated` when nothing changed, so a nightly rebuild does
  // not look like a new list.
  const unchanged = previous && JSON.stringify(previous.models) === JSON.stringify(next.models);
  if (unchanged) {
    console.log(`no change (${models.length} models)`);
    return;
  }
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${OUT}: ${models.length} models, ${Buffer.byteLength(text)} bytes`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e) => {
    console.error(String((e && e.message) || e));
    process.exit(1);
  });
}
